export function getCustomerById(customerId: string) {
  return crmCustomers.find((customer) => customer.id === customerId);
}

export function getCaseById(caseId: string) {
  return crmCases.find((item) => item.id === caseId);
}

export function getThreadByCaseId(caseId: string) {
  return crmThreads.find((thread) => thread.caseId === caseId);
}

export function getCustomerCases(customerId: string) {
  return crmCases.filter((item) => item.customerId === customerId);
}

export function getCustomerThreads(customerId: string) {
  return crmThreads.filter((thread) => thread.customerId === customerId);
}
